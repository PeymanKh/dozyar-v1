export function findGuide(id: string): FoodGuide | undefined {
  return GUIDES.find((g) => g.id === id);
}

/** The guides that answer these symptoms, in the order of the list. */
export function guidesFor(symptoms: SymptomId[]): FoodGuide[] {
  return GUIDES.filter((g) => g.symptoms.some((s) => symptoms.includes(s)));
}
