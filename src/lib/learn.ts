export function findLesson(id: string): Lesson | undefined {
  return LESSONS.find((l) => l.id === id);
}

/** The first lesson on the path not read yet; null when all are read. */
export function nextLesson(read: string[]): Lesson | null {
  const id = LESSON_PATH.find((l) => !read.includes(l));
  return id ? findLesson(id)! : null;
}

export function lessonsIn(category: LessonCategory): Lesson[] {
  return LESSON_PATH.map((id) => findLesson(id)!).filter((l) => l.category === category);
}
